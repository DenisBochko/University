from math import sqrt


# Требуемая точность
EPS = 1e-4

# Матрица вторых производных (матрица Гессе) для квадратичной функции
# Она постоянна: не зависит от текущих x1 и x2
H = ((8.0, 4.0), (4.0, 12.0))

# Возвращает значение целевой функции в точке x = (x1, x2)
def f(x):
    x1, x2 = x
    return 4 * x1**2 + 4 * x1 * x2 + 6 * x2**2 - 17 * x1

# Вычисляет градиент функции.
# Градиент показывает направление самого быстрого возрастания функции.
# Поэтому для уменьшения f нужно идти в противоположную сторону: -grad(f).
# df/dx1 = 8*x1 + 4*x2 - 17
# df/dx2 = 4*x1 + 12*x2
def grad(x):
    x1, x2 = x
    return (8 * x1 + 4 * x2 - 17, 4 * x1 + 12 * x2) # Просто берём производные по иксам.

# Евклидова длина вектора sqrt(v1^2 + v2^2)
def norm(v):
    return sqrt(v[0] ** 2 + v[1] ** 2)

# Метод скорейшего градиентного спуска
# На каждой итерации:
# - находим градиент g;
# - выбираем направление -g;
# - рассчитываем лучший шаг alpha именно для квадратичной функции;
# - переходим в новую точку.
def steepest_descent(x=(0.0, 0.0)):
    iterations = 0

    # Пока градиент не близок к нулю, мы ещё не достаточно близко к минимуму.
    while norm(grad(x)) > EPS:
        g = grad(x)

        # Умножаем матрицу Гессе H на вектор градиента g: hg = H*g.
        hg = (
            H[0][0] * g[0] + H[0][1] * g[1],
            H[1][0] * g[0] + H[1][1] * g[1],
        )

        # Точный размер шага для данной квадратичной функции.
        alpha = (g[0] ** 2 + g[1] ** 2) / (g[0] * hg[0] + g[1] * hg[1])

        # Делаем шаг против градиента, потому что ищем минимум.
        x = (x[0] - alpha * g[0], x[1] - alpha * g[1])
        iterations += 1

    return x, f(x), iterations, norm(grad(x))

# Метод Ньютона
# В отличие от градиентного метода, здесь используются не только первые,
# но и вторые производные. Направление шага равно H^(-1) * grad(f).
def newton(x=(0.0, 0.0)):
    # Сначала находим определитель матрицы H.
    det = H[0][0] * H[1][1] - H[0][1] * H[1][0]

    # Формула обратной матрицы 2x2: H^(-1).
    h_inv = (
        (H[1][1] / det, -H[0][1] / det),
        (-H[1][0] / det, H[0][0] / det),
    )

    iterations = 0
    while norm(grad(x)) > EPS:
        g = grad(x)

        # Вычисляем ньютоновское направление: step = H^(-1) * g.
        step = (
            h_inv[0][0] * g[0] + h_inv[0][1] * g[1],
            h_inv[1][0] * g[0] + h_inv[1][1] * g[1],
        )

        # Двигаемся в противоположную сторону от найденного направления.
        x = (x[0] - step[0], x[1] - step[1])
        iterations += 1

    return x, f(x), iterations, norm(grad(x))

# Метод Хука – Дживса (метод без производных).
# Он пробует сдвинуться по каждой координате на шаг delta.
# Если значение функции уменьшается, новая точка сохраняется.
# Если улучшения нет, шаг уменьшается в два раза.
def hooke_jeeves(x=(0.0, 0.0), delta=1.0):
    def explore(base, step):
        # Исследующий поиск: пробуем +/- step по каждой из двух координат

        point = list(base)

        # По очереди проверяем x1 и x2.
        for coordinate in range(2):
            # Копируем текущую точку и увеличиваем одну координату на step.
            candidate = point.copy()
            candidate[coordinate] += step

            # Если функция стала меньше, то оставляем новую точку.
            if f(candidate) < f(point):
                point = candidate
                continue

            # Если увеличение не улучшило результат,
            # пробуем уменьшить эту координату на step.
            candidate = point.copy()
            candidate[coordinate] -= step

            # Если так функция уменьшилась, то сохраняем новую точку.
            if f(candidate) < f(point):
                point = candidate

        return tuple(point)

    # base это текущая базовая точка.
    base = x
    iterations = 0

    # Пока шаг достаточно большой, продолжаем поиск.
    while delta > EPS:
        # Проверяем, можно ли улучшить точку небольшими шагами
        # по x1 и x2.
        explored = explore(base, delta)
        iterations += 1

        # Если новая точка лучше старой:
        if f(explored) < f(base):
            # Делаем шаг: продолжаем двигаться в направлении найденного улучшения.
            pattern = (
                2 * explored[0] - base[0],
                2 * explored[1] - base[1],
            )

            # В новой точке снова ищем улучшение.
            trial = explore(pattern, delta)

            # Оставляем лучшую точку из двух вариантов.
            if f(trial) < f(explored):
                base = trial
            else:
                base = explored

        # Если улучшения не нашлось, уменьшаем шаг в 2 раза.
        else:
            delta /= 2

    # Возвращаем точку минимума, значение функции,
    # число итераций и конечный размер шага.
    return base, f(base), iterations, delta


# Выводит результат в терминал.
def show(name, result, extra_name, extra_value):
    x, value, iterations, _ = result

    print(name)
    print(f"x1 = {x[0]:.6f}")
    print(f"x2 = {x[1]:.6f}")
    print(f"f_min = {value:.6f}")
    print(f"Итераций = {iterations}")
    print(f"{extra_name} = {extra_value:.8f}\n")

if __name__ == "__main__":
    # Запускаем три метода из начальной точки (0, 0).
    sd = steepest_descent()
    nt = newton()
    hj = hooke_jeeves()

    # Выводим результаты каждого метода.
    show("Метод скорейшего градиентного спуска", sd, "grad f", sd[3])
    show("Метод Ньютона", nt, "grad f", nt[3])
    show("Метод Хука – Дживса", hj, "Конечный шаг", hj[3])
