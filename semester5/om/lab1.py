from math import sqrt

EPS = 0.0001  # Требуемая точность поиска.


def volume(x):
    # После вырезания квадратов высота равна x,
    # а размеры основания: 30 - 2x и 14 - 2x.
    return x * (30 - 2 * x) * (14 - 2 * x)


def f(x):
    # Методы ищут минимум.
    # Поэтому максимум объёма V(x) заменяем минимумом -V(x).
    return -volume(x)

# Метод золотого сечения.
# На каждом шаге выбираются две точки внутри интервала [a; b].
# Значения функции в этих точках показывают, в какой части интервала
# минимум точно отсутствует. Эта часть отбрасывается.
# Интервал постепенно сужается до точности EPS.
def golden_section(a, b):
    # Метод золотого сечения.
    # a и b — левая и правая границы текущего интервала поиска.

    # Коэффициент золотого сечения: примерно 0.618.
    k = (sqrt(5) - 1) / 2

    # Выбираем две внутренние точки интервала.
    x1 = b - k * (b - a)
    x2 = a + k * (b - a)

    iterations = 0

    # Работаем, пока длина интервала больше требуемой точности.
    while b - a > EPS:
        iterations += 1

        # Если в x1 функция меньше, минимум находится левее x2.
        # Поэтому правую часть интервала можно отбросить.
        if f(x1) < f(x2):
            b = x2

            # Старая точка x1 становится новой x2:
            # её значение функции уже известно.
            x2 = x1

            # Вычисляем только одну новую точку.
            x1 = b - k * (b - a)

        # Иначе минимум находится правее x1,
        # поэтому отбрасываем левую часть интервала.
        else:
            a = x1
            x1 = x2
            x2 = a + k * (b - a)

    # За приближённый минимум берём середину финального интервала.
    return (a + b) / 2, iterations


# Метод квадратичной аппроксимации Пауэлла.
# По трём точкам и значениям функции в них строится приближающая парабола.
# Вершина этой параболы считается новым приближением к минимуму.
# Затем выбираются новые три точки, которые окружают минимум,
# и процесс повторяется до точности EPS.
def powell(a, b, c):
    # Метод квадратичной аппроксимации Пауэлла.
    # a < b < c — три точки, между которыми расположен минимум.

    iterations = 0

    # Пока крайние точки расположены дальше EPS друг от друга,
    # продолжаем уточнять положение минимума.
    while c - a > EPS:
        # Значения функции в трёх текущих точках.
        fa = f(a)
        fb = f(b)
        fc = f(c)

        # По трём точкам строится приближающая парабола.
        # Формула ниже даёт x-координату её вершины.
        numerator = (
            (b**2 - c**2) * fa
            + (c**2 - a**2) * fb
            + (a**2 - b**2) * fc
        )
        denominator = 2 * (
            (b - c) * fa
            + (c - a) * fb
            + (a - b) * fc
        )
        x = numerator / denominator
        fx = f(x)

        iterations += 1

        # Обновляем три точки так, чтобы минимум
        # по-прежнему оставался между a и c.
        if x < b:
            # Новая точка лежит слева от текущей лучшей точки b.
            if fx < fb:
                # Новая точка лучше: сдвигаем правую границу к b.
                c, b = b, x
            else:
                # Новая точка хуже: отбрасываем левую часть.
                a = x
        else:
            # Новая точка лежит справа от текущей лучшей точки b.
            if fx < fb:
                # Новая точка лучше: сдвигаем левую границу к b.
                a, b = b, x
            else:
                # Новая точка хуже: отбрасываем правую часть.
                c = x

    # b — лучшее приближение к точке минимума функции f(x).
    return b, iterations


# Начальный интервал для метода золотого сечения.
x_golden, n_golden = golden_section(0, 7)

# Три начальные точки для метода Пауэлла.
x_powell, n_powell = powell(0, 3.5, 6.9)

print("Золотое сечение:")
print(f"x = {x_golden:.6f} см")
print(f"Vmax = {volume(x_golden):.6f} см³")
print(f"Итераций: {n_golden}\n")

print("Метод Пауэлла:")
print(f"x = {x_powell:.6f} см")
print(f"Vmax = {volume(x_powell):.6f} см³")
print(f"Итераций: {n_powell}")

# Проверяем, что оба метода нашли x = 3 с требуемой точностью.
assert abs(x_golden - 3) < EPS
assert abs(x_powell - 3) < EPS
